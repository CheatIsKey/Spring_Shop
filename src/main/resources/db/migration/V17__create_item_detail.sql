-- (선택) 주석
COMMENT ON TABLE  public.item_detail IS 'Item 상세(1:1)';
COMMENT ON COLUMN public.item_detail.description IS '상세 설명';
COMMENT ON COLUMN public.item_detail.spec        IS '스펙 정보';
